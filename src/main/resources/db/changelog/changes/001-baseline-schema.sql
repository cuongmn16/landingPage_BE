CREATE TABLE IF NOT EXISTS units (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50)  NOT NULL UNIQUE,
    name            VARCHAR(150) NOT NULL,
    total_personnel INTEGER      NOT NULL,
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS employees (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code     VARCHAR(50)  NOT NULL UNIQUE,
    email             VARCHAR(100) NOT NULL UNIQUE,
    full_name         VARCHAR(150) NOT NULL,
    password          VARCHAR(255),
    role              VARCHAR(20)  NOT NULL,
    approval_status   VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    is_email_verified BOOLEAN      NOT NULL,
    unit_id           BIGINT       NOT NULL REFERENCES units (id),
    created_at        TIMESTAMP(6),
    updated_at        TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS missions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50)  NOT NULL UNIQUE,
    title       VARCHAR(200) NOT NULL,
    description TEXT,
    is_open     BOOLEAN      NOT NULL,
    start_time  TIMESTAMP(6),
    end_time    TIMESTAMP(6),
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS submissions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id           BIGINT       NOT NULL REFERENCES employees (id),
    mission_id            BIGINT       NOT NULL REFERENCES missions (id),
    long_text_answer      TEXT,
    selected_options_json TEXT,
    ordered_data_json     TEXT,
    evidence_source       TEXT,
    witness_name          VARCHAR(200),
    status                VARCHAR(30)  NOT NULL,
    score                 DOUBLE PRECISION,
    submission_time       TIMESTAMP(6) NOT NULL,
    last_updated_at       TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_employee_mission UNIQUE (employee_id, mission_id)
);

CREATE TABLE IF NOT EXISTS submission_attachments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id      BIGINT        NOT NULL REFERENCES submissions (id),
    original_file_name VARCHAR(255)  NOT NULL,
    object_key         VARCHAR(500)  NOT NULL,
    file_url           VARCHAR(1000),
    content_type       VARCHAR(100),
    file_size_bytes    BIGINT        NOT NULL,
    uploaded_at        TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS system_rule_configs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key   VARCHAR(100) NOT NULL UNIQUE,
    rule_type    VARCHAR(50)  NOT NULL,
    config_value VARCHAR(255) NOT NULL,
    description  VARCHAR(255),
    updated_at   TIMESTAMP(6)
);

